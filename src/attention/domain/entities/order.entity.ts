import { OrderSource } from '../enums/order-source.enum.js';
import { OrderStatus } from '../enums/order-status.enum.js';
import {
  EmptyOrderError,
  OrderAlreadyFinishedError,
  OrderItemHasPaymentsError,
  OrderItemNotFoundError,
  OrderNotSubmittedError,
  StaleOrderItemVersionError,
} from '../exceptions/attention.errors.js';
import type { StatusCatalog } from '../status-catalog.js';
import type { StatusRef } from '../workflows.js';
import { OrderItem } from './order-item.entity.js';
import type { OrderItemStatusHistory } from './order-item-status-history.entity.js';

const DROPPED_ITEM_STATUSES = [OrderStatus.REJECTED, OrderStatus.CANCELLED];
/** Leaving the bill: not allowed once the item is covered by a payment. */
const DROPPING_STATUSES = DROPPED_ITEM_STATUSES;
const FINAL_STATUSES = [OrderStatus.SERVED, OrderStatus.CANCELLED];

export interface OrderProps {
  id: string;
  attentionId: string;
  /** Client-generated id that makes submitting the same order idempotent. */
  requestId: string;
  source: OrderSource;
  submittedByUserId: string | null;
  submittedByParticipantId: string | null;
  status: StatusRef<OrderStatus>;
  submittedAt: Date;
  confirmedAt: Date | null;
  createdAt: Date;
  updatedAt: Date;
}

export interface OrderLine {
  /** Ids are generated by the caller (the domain stays deterministic). */
  itemId: string;
  historyId: string;
  productId: string;
  /** Catalog name and price at order time, frozen on the item. */
  productName: string;
  unitPrice: number;
  quantity: number;
  customerNote?: string | null;
}

/** What changed since the order was loaded, for the repository to persist. */
export interface OrderChanges {
  newItems: OrderItem[];
  /** Existing items whose status changed; saved only if still at `version`. */
  changedItems: OrderItem[];
  history: OrderItemStatusHistory[];
}

/**
 * One order (comanda / ronda) of an attention, sent from the cart (CUSTOMER)
 * or registered by a waiter. An attention has one or more orders; finishing
 * or cancelling one never closes or cancels the attention.
 *
 * Aggregate root of its items: every item change goes through the order, so
 * the order status always matches its items (see syncWithItems).
 */
export class Order {
  private readonly newItemIds = new Set<string>();
  private readonly changedItemIds = new Set<string>();
  private pendingHistory: OrderItemStatusHistory[] = [];

  private constructor(
    private props: OrderProps,
    private readonly orderItems: OrderItem[],
  ) {}

  static submit(params: {
    id: string;
    attentionId: string;
    requestId: string;
    source: OrderSource;
    /** The restaurant's initial order status (canonical SUBMITTED). */
    status: StatusRef<OrderStatus>;
    submittedByUserId?: string | null;
    submittedByParticipantId?: string | null;
    lines: OrderLine[];
  }): Order {
    if (params.lines.length === 0) {
      throw new EmptyOrderError();
    }
    const now = new Date();
    const order = new Order(
      {
        id: params.id,
        attentionId: params.attentionId,
        requestId: params.requestId,
        source: params.source,
        submittedByUserId: params.submittedByUserId ?? null,
        submittedByParticipantId: params.submittedByParticipantId ?? null,
        status: params.status,
        submittedAt: now,
        confirmedAt: null,
        createdAt: now,
        updatedAt: now,
      },
      [],
    );
    for (const line of params.lines) {
      const { item, history } = OrderItem.create({
        id: line.itemId,
        historyId: line.historyId,
        status: params.status,
        orderId: params.id,
        productId: line.productId,
        productName: line.productName,
        unitPrice: line.unitPrice,
        quantity: line.quantity,
        customerNote: line.customerNote,
        requestedByParticipantId: params.submittedByParticipantId,
      });
      order.orderItems.push(item);
      order.newItemIds.add(item.id);
      order.pendingHistory.push(history);
    }
    return order;
  }

  static fromPersistence(props: OrderProps, items: OrderItem[]): Order {
    return new Order(props, [...items]);
  }

  get items(): readonly OrderItem[] {
    return this.orderItems;
  }

  /**
   * Moves one item along the kitchen flow and re-derives the order status.
   * `expectedVersion` is the item version the caller read; `paidItemIds` the
   * items covered by a payment, which can't be rejected or cancelled.
   * Returns the canonical state the item had before.
   */
  changeItemStatus(
    itemId: string,
    target: StatusRef<OrderStatus>,
    options: {
      historyId: string;
      statuses: StatusCatalog<OrderStatus>;
      expectedVersion?: number;
      reason?: string | null;
      changedByUserId?: string | null;
      paidItemIds?: ReadonlySet<string>;
    },
  ): OrderStatus {
    const item = this.orderItems.find((candidate) => candidate.id === itemId);
    if (!item) {
      throw new OrderItemNotFoundError(itemId);
    }
    if (
      options.expectedVersion !== undefined &&
      options.expectedVersion !== item.version
    ) {
      throw new StaleOrderItemVersionError(itemId);
    }
    if (
      DROPPING_STATUSES.includes(target.canonicalState) &&
      options.paidItemIds?.has(itemId)
    ) {
      throw new OrderItemHasPaymentsError();
    }
    const previous = item.currentStatus;
    this.record(
      item,
      item.changeStatus(target, {
        historyId: options.historyId,
        reason: options.reason,
        changedByUserId: options.changedByUserId,
      }),
    );
    this.syncWithItems(options.statuses);
    return previous;
  }

  /**
   * Cancels the whole order (e.g. the table changed its mind) while nothing
   * of it has been served: its pending items are cancelled with history.
   */
  cancel(
    cancelled: StatusRef<OrderStatus>,
    options: {
      statuses: StatusCatalog<OrderStatus>;
      nextHistoryId: () => string;
      reason: string;
      changedByUserId?: string | null;
      paidItemIds?: ReadonlySet<string>;
    },
  ): void {
    if (
      this.isFinished ||
      this.orderItems.some((item) => item.currentStatus === OrderStatus.SERVED)
    ) {
      throw new OrderAlreadyFinishedError(this.status);
    }
    const pending = this.orderItems.filter((item) => item.isBillable);
    if (pending.some((item) => options.paidItemIds?.has(item.id))) {
      throw new OrderItemHasPaymentsError();
    }
    for (const item of pending) {
      this.record(
        item,
        item.changeStatus(cancelled, {
          historyId: options.nextHistoryId(),
          reason: options.reason,
          changedByUserId: options.changedByUserId,
        }),
      );
    }
    this.syncWithItems(options.statuses);
  }

  /** Rejecting or cancelling an item takes it off the bill. */
  static dropsFromBill(target: StatusRef<OrderStatus>): boolean {
    return DROPPING_STATUSES.includes(target.canonicalState);
  }

  /** Billable items: the ones a payment could cover. */
  get billableItemIds(): string[] {
    return this.orderItems
      .filter((item) => item.isBillable)
      .map((item) => item.id);
  }

  /** Hands the pending changes to the repository and forgets them. */
  pullChanges(): OrderChanges {
    const changes: OrderChanges = {
      newItems: this.orderItems.filter((item) => this.newItemIds.has(item.id)),
      changedItems: this.orderItems.filter(
        (item) =>
          this.changedItemIds.has(item.id) && !this.newItemIds.has(item.id),
      ),
      history: this.pendingHistory,
    };
    this.newItemIds.clear();
    this.changedItemIds.clear();
    this.pendingHistory = [];
    return changes;
  }

  private record(item: OrderItem, history: OrderItemStatusHistory): void {
    this.changedItemIds.add(item.id);
    this.pendingHistory.push(history);
  }

  confirm(statuses: StatusCatalog<OrderStatus>): void {
    if (this.status !== OrderStatus.SUBMITTED) {
      throw new OrderNotSubmittedError();
    }
    this.props.status = statuses.defaultFor(OrderStatus.CONFIRMED);
    this.props.confirmedAt = new Date();
    this.props.updatedAt = new Date();
  }

  /**
   * Derives the operational state from the canonical states of its items:
   * every item rejected/cancelled -> CANCELLED; the remaining ones all served
   * -> SERVED, all ready or served -> READY, any started -> IN_PREPARATION;
   * none started -> stays SUBMITTED / CONFIRMED. The status row is the
   * restaurant's first active one for that state.
   */
  private syncWithItems(statuses: StatusCatalog<OrderStatus>): void {
    const active = this.orderItems
      .map((item) => item.currentStatus)
      .filter((state) => !DROPPED_ITEM_STATUSES.includes(state));
    const next = Order.deriveState(active);
    if (next && next !== this.status) {
      this.props.status = statuses.defaultFor(next);
      this.props.updatedAt = new Date();
    }
  }

  private static deriveState(active: OrderStatus[]): OrderStatus | null {
    if (active.length === 0) {
      return OrderStatus.CANCELLED;
    }
    if (active.every((state) => state === OrderStatus.SERVED)) {
      return OrderStatus.SERVED;
    }
    if (
      active.every(
        (state) => state === OrderStatus.READY || state === OrderStatus.SERVED,
      )
    ) {
      return OrderStatus.READY;
    }
    if (active.some((state) => state !== OrderStatus.SUBMITTED)) {
      return OrderStatus.IN_PREPARATION;
    }
    return null;
  }

  get isFinished(): boolean {
    return FINAL_STATUSES.includes(this.status);
  }

  get id(): string {
    return this.props.id;
  }
  get attentionId(): string {
    return this.props.attentionId;
  }
  get requestId(): string {
    return this.props.requestId;
  }
  get source(): OrderSource {
    return this.props.source;
  }
  get submittedByUserId(): string | null {
    return this.props.submittedByUserId;
  }
  get submittedByParticipantId(): string | null {
    return this.props.submittedByParticipantId;
  }
  /** Canonical state of the current status. */
  get status(): OrderStatus {
    return this.props.status.canonicalState;
  }
  get statusId(): string {
    return this.props.status.id;
  }
  get submittedAt(): Date {
    return this.props.submittedAt;
  }
  get confirmedAt(): Date | null {
    return this.props.confirmedAt;
  }
  get createdAt(): Date {
    return this.props.createdAt;
  }
  get updatedAt(): Date {
    return this.props.updatedAt;
  }
}
